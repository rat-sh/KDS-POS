CREATE TABLE payment_refund (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES order_header(id),
    payment_id BIGINT NOT NULL UNIQUE REFERENCES payment(id),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    status VARCHAR(20) NOT NULL CHECK (status IN ('REFUND_PENDING', 'COMPLETED')),
    reason VARCHAR(500) NOT NULL,
    initiated_by BIGINT NOT NULL REFERENCES app_user(id),
    completed_by BIGINT REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    completed_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    CHECK ((status = 'REFUND_PENDING' AND completed_by IS NULL AND completed_at IS NULL)
        OR (status = 'COMPLETED' AND completed_by IS NOT NULL AND completed_at IS NOT NULL))
);

CREATE INDEX payment_refund_status_idx ON payment_refund(status, created_at DESC);

CREATE TABLE stock_adjustment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id BIGINT NOT NULL REFERENCES menu_item(id),
    quantity_delta INTEGER NOT NULL CHECK (quantity_delta <> 0),
    stock_after INTEGER NOT NULL CHECK (stock_after >= 0),
    reason VARCHAR(250) NOT NULL,
    adjusted_by BIGINT NOT NULL REFERENCES app_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX stock_adjustment_item_time_idx ON stock_adjustment(item_id, created_at DESC, id DESC);
