CREATE TABLE app_user (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(80) NOT NULL UNIQUE,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CASHIER', 'KITCHEN', 'MANAGER', 'ADMIN')),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE station (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    display_order INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0
);

CREATE TABLE user_station (
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    station_id BIGINT NOT NULL REFERENCES station(id),
    PRIMARY KEY (user_id, station_id)
);

CREATE TABLE menu_category (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(80) NOT NULL UNIQUE,
    gst_rate NUMERIC(5,2) NOT NULL CHECK (gst_rate >= 0 AND gst_rate <= 100),
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE menu_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES menu_category(id),
    name VARCHAR(120) NOT NULL,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    available BOOLEAN NOT NULL DEFAULT TRUE,
    track_stock BOOLEAN NOT NULL DEFAULT FALSE,
    stock_quantity INTEGER CHECK (stock_quantity IS NULL OR stock_quantity >= 0),
    target_prep_seconds INTEGER NOT NULL CHECK (target_prep_seconds > 0),
    version BIGINT NOT NULL DEFAULT 0,
    archived BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (category_id, name)
);

CREATE TABLE menu_item_station (
    item_id BIGINT NOT NULL REFERENCES menu_item(id) ON DELETE CASCADE,
    station_id BIGINT NOT NULL REFERENCES station(id),
    PRIMARY KEY (item_id, station_id)
);

CREATE TABLE modifier_group (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    selection_type VARCHAR(12) NOT NULL CHECK (selection_type IN ('SINGLE', 'MULTIPLE')),
    min_select INTEGER NOT NULL DEFAULT 0 CHECK (min_select >= 0),
    max_select INTEGER NOT NULL DEFAULT 1 CHECK (max_select >= min_select)
);

CREATE TABLE menu_modifier (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT NOT NULL REFERENCES modifier_group(id) ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    price_delta NUMERIC(12,2) NOT NULL DEFAULT 0,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE item_modifier_group (
    item_id BIGINT NOT NULL REFERENCES menu_item(id) ON DELETE CASCADE,
    group_id BIGINT NOT NULL REFERENCES modifier_group(id),
    PRIMARY KEY (item_id, group_id)
);

CREATE TABLE order_header (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(32) NOT NULL UNIQUE,
    business_date DATE NOT NULL,
    token INTEGER NOT NULL,
    order_type VARCHAR(20) NOT NULL CHECK (order_type IN ('DINE_IN', 'TAKEAWAY', 'DELIVERY')),
    table_name VARCHAR(40),
    status VARCHAR(20) NOT NULL CHECK (status IN ('CREATED', 'IN_KITCHEN', 'READY', 'CANCELLED', 'COMPLETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    paid_at TIMESTAMPTZ,
    ready_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    rush BOOLEAN NOT NULL DEFAULT FALSE,
    priority_reason VARCHAR(250),
    note VARCHAR(500),
    created_by BIGINT NOT NULL REFERENCES app_user(id),
    cancelled_at TIMESTAMPTZ,
    cancelled_by BIGINT REFERENCES app_user(id),
    cancellation_reason VARCHAR(500),
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (business_date, token)
);

CREATE TABLE order_line (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES order_header(id) ON DELETE CASCADE,
    item_id BIGINT NOT NULL REFERENCES menu_item(id),
    item_name VARCHAR(120) NOT NULL,
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(12,2) NOT NULL,
    gst_rate NUMERIC(5,2) NOT NULL,
    target_prep_seconds INTEGER NOT NULL
);

CREATE TABLE order_line_modifier (
    order_line_id BIGINT NOT NULL REFERENCES order_line(id) ON DELETE CASCADE,
    modifier_id BIGINT NOT NULL REFERENCES menu_modifier(id),
    modifier_name VARCHAR(100) NOT NULL,
    price_delta NUMERIC(12,2) NOT NULL,
    PRIMARY KEY (order_line_id, modifier_id)
);

CREATE TABLE kitchen_ticket (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES order_header(id) ON DELETE CASCADE,
    station_id BIGINT NOT NULL REFERENCES station(id),
    status VARCHAR(20) NOT NULL CHECK (status IN ('NEW', 'ACCEPTED', 'IN_PROGRESS', 'DONE', 'SERVED', 'CANCELLED')),
    target_seconds INTEGER NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    accepted_at TIMESTAMPTZ,
    accepted_by BIGINT REFERENCES app_user(id),
    started_at TIMESTAMPTZ,
    done_at TIMESTAMPTZ,
    served_at TIMESTAMPTZ,
    served_by BIGINT REFERENCES app_user(id),
    cancelled_acknowledged_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (order_id, station_id)
);

CREATE TABLE ticket_line (
    ticket_id BIGINT NOT NULL REFERENCES kitchen_ticket(id) ON DELETE CASCADE,
    order_line_id BIGINT NOT NULL REFERENCES order_line(id) ON DELETE CASCADE,
    PRIMARY KEY (ticket_id, order_line_id)
);

CREATE TABLE payment (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL UNIQUE REFERENCES order_header(id),
    method VARCHAR(10) NOT NULL CHECK (method IN ('CASH', 'UPI', 'CARD')),
    amount NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    tendered NUMERIC(12,2),
    reference VARCHAR(120),
    paid_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    paid_by BIGINT NOT NULL REFERENCES app_user(id)
);

CREATE TABLE refresh_token (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE idempotency_record (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idempotency_key VARCHAR(120) NOT NULL UNIQUE,
    request_hash CHAR(64) NOT NULL,
    response_body JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE audit_entry (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor_id BIGINT REFERENCES app_user(id),
    actor_role VARCHAR(20) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id BIGINT NOT NULL,
    action VARCHAR(60) NOT NULL,
    correlation_id VARCHAR(80),
    reason VARCHAR(500)
);

CREATE INDEX order_created_idx ON order_header(created_at DESC);
CREATE INDEX order_business_idx ON order_header(business_date, status);
CREATE INDEX ticket_station_status_idx ON kitchen_ticket(station_id, status, created_at);
CREATE INDEX audit_time_idx ON audit_entry(occurred_at DESC);
CREATE INDEX refresh_user_idx ON refresh_token(user_id, expires_at);

